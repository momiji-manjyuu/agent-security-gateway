#!/usr/bin/env bash
# ホストのネットワーク隔離 (root, 冪等)。nftables `inet asg` テーブルを専用 asg-nft.service で読み込む
# (Ubuntu の nftables.service とは独立)。方針 (docs/guides/reverse-tunnel.md のトンネル構成と整合):
#  - ワーカー (BRIDGE) → インターネットは NAT で許可 (LAN/RFC1918/特殊アドレス以外)
#  - ワーカー → BRIDGE_IP:ASG_PORT (tcp) は許可: 逆トンネルの終点 (ssh -R が worker ホストの
#    BRIDGE_IP:ASG_PORT で待ち受け、ゲートウェイの 127.0.0.1:ASG_PORT へ転送する)
#  - ワーカー → LAN/RFC1918/特殊アドレスは遮断。ASG ハブを LAN 上で直接運用する場合の例外が
#    ASG_IP:ASG_PORT (tcp, forward)。トンネル構成では未使用
#  - ワーカー IPv6 は全遮断、ワーカー → ホスト自身への新規接続も (BRIDGE_IP:ASG_PORT を除き) 遮断
#  - ホスト → LAN の新規接続は ASG_IP と LAN_GW の DNS/DHCP のみ
set -euo pipefail
[[ $EUID -eq 0 ]] || { echo "run as root"; exit 1; }
CONF=${ASG_GOLDEN_CONF:-$(dirname "$(readlink -f "$0")")/golden.env}; [[ -f $CONF ]] && . "$CONF"
: "${WAN_IF:?set WAN_IF}" "${LAN_CIDR:?set LAN_CIDR}" "${LAN_GW:?set LAN_GW}" "${ASG_IP:?set ASG_IP}"
BR=${BRIDGE:-asgbr0}; WNET=${WORKER_CIDR:-10.90.0.0/24}; PORT=${ASG_PORT:-8788}; BRIP=${BRIDGE_IP:-10.90.0.1}
OUT=${NFT_FILE:-/etc/nftables.d/asg.nft}
install -d "$(dirname "$OUT")"
TMP=$(mktemp); trap 'rm -f "$TMP"' EXIT
cat > "$TMP" <<N
#!/usr/sbin/nft -f
# generated by host-network.sh — edit golden.env and re-run instead of editing this file
define WAN      = "$WAN_IF"
define WBR      = "$BR"
define WNET     = $WNET
define LAN      = $LAN_CIDR
define LAN_GW   = $LAN_GW
define ASG_HUB  = $ASG_IP
define ASG_PORT = $PORT
define BRIDGEIP = $BRIP
table inet asg
delete table inet asg
table inet asg {
  set v4_blocked {
    type ipv4_addr; flags interval
    elements = { 0.0.0.0/8, 10.0.0.0/8, 100.64.0.0/10, 127.0.0.0/8, 169.254.0.0/16,
                 172.16.0.0/12, 192.0.0.0/24, 192.0.2.0/24, 192.168.0.0/16, 198.18.0.0/15,
                 198.51.100.0/24, 203.0.113.0/24, 224.0.0.0/4, 240.0.0.0/4 }
  }
  chain input {
    type filter hook input priority -10; policy accept;
    iifname \$WBR ip daddr \$BRIDGEIP tcp dport \$ASG_PORT accept
    iifname \$WBR ct state established,related accept
    iifname \$WBR counter drop
  }
  chain forward {
    type filter hook forward priority -10; policy drop;
    ct state invalid drop
    oifname \$WBR ct state established,related accept
    oifname \$WBR counter drop
    iifname \$WBR oifname \$WAN ip daddr \$ASG_HUB tcp dport \$ASG_PORT accept
    iifname \$WBR ip daddr \$LAN counter drop
    iifname \$WBR ip daddr @v4_blocked counter drop
    iifname \$WBR meta nfproto ipv6 counter drop
    iifname \$WBR oifname \$WAN ip saddr \$WNET accept
    counter drop
  }
  chain output {
    type filter hook output priority -10; policy accept;
    oifname "lo" accept
    ct state established,related accept
    ip daddr \$LAN_GW udp dport { 53, 67 } accept
    ip daddr \$LAN_GW tcp dport 53 accept
    ip daddr \$ASG_HUB accept
    ${LAN_BCAST:+ip daddr $LAN_BCAST udp dport 67 accept}
    ip daddr 255.255.255.255 udp dport 67 accept
    ip daddr \$LAN counter drop
    ip6 daddr fc00::/7 counter drop
    meta nfproto ipv6 oifname != "lo" counter drop
  }
  chain postrouting {
    type nat hook postrouting priority srcnat; policy accept;
    oifname \$WAN ip saddr \$WNET masquerade
  }
}
N
nft -c -f "$TMP"
install -m0644 "$TMP" "$OUT"
cat > /etc/systemd/system/asg-nft.service <<U
[Unit]
Description=ASG isolation nftables table (inet asg)
After=network-pre.target ufw.service
Before=network-online.target
[Service]
Type=oneshot
ExecStart=/usr/sbin/nft -f $OUT
ExecStop=/usr/sbin/nft delete table inet asg
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
U
printf 'net.ipv4.ip_forward=1\nnet.ipv6.conf.%s.disable_ipv6=1\n' "$BR" > /etc/sysctl.d/61-asg-forward.conf
sysctl -q -p /etc/sysctl.d/61-asg-forward.conf || true
# ufw 使用時 (routed=deny) はワーカー転送を明示許可。フィルタは inet asg が担う
if command -v ufw >/dev/null && ufw status | grep -q 'Status: active'; then
  ufw route allow in on "$BR" out on "$WAN_IF" comment 'ASG workers NAT (filtered by inet asg)'; fi
systemctl daemon-reload; systemctl enable asg-nft.service; systemctl restart asg-nft.service
nft list table inet asg >/dev/null && echo "inet asg loaded ($OUT)"
