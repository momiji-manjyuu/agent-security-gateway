#!/bin/sh
# Run an isolated Linux lab VM with plain QEMU. Works on macOS (Apple Silicon or Intel, HVF) and Linux (KVM).
# This is also what UTM runs underneath; use it when you want a scriptable, headless lab on a Mac.
#   new-lab-vm.sh --name NAME --base-image <cloud image qcow2 for THIS cpu> --pubkey lab.pub [--ssh-port 2222] [--dry-run]
#     Apple Silicon / arm64:  noble-server-cloudimg-arm64.img      Intel / amd64:  noble-server-cloudimg-amd64.img
# Network: user-mode networking with restrict=on. The guest cannot reach the host, the LAN or the internet.
# The only opening is a host-side forward 127.0.0.1:<ssh-port> -> guest:22 for management.
set -eu
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
common="$here/../common"
name="" base="" pubkey="" mem=8192 cpus=4 disk=60 ssh_port=2222 root="${ASG_LAB_ROOT:-$HOME/asg-lab}" dry=0 fw=""

die() { echo "asg-lab: $*" >&2; exit 1; }
while [ $# -gt 0 ]; do
  case "$1" in
    --name) name=$2; shift 2 ;; --base-image) base=$2; shift 2 ;; --pubkey) pubkey=$2; shift 2 ;;
    --memory-mb) mem=$2; shift 2 ;; --cpus) cpus=$2; shift 2 ;; --disk-gb) disk=$2; shift 2 ;;
    --ssh-port) ssh_port=$2; shift 2 ;; --root) root=$2; shift 2 ;; --firmware) fw=$2; shift 2 ;; --dry-run) dry=1; shift ;;
    *) die "unknown argument: $1" ;;
  esac
done
[ -n "$name" ] && [ -n "$base" ] && [ -n "$pubkey" ] || die "need --name, --base-image, --pubkey"
[ -r "$base" ] || die "cannot read base image"
run() { if [ "$dry" -eq 1 ]; then echo "+ $*"; else "$@"; fi; }

os=$(uname -s); arch=$(uname -m)
case "$arch" in
  arm64|aarch64) qemu=qemu-system-aarch64; machine="virt,highmem=on"; cpu_model="host"
    [ -n "$fw" ] || { for f in /opt/homebrew/share/qemu/edk2-aarch64-code.fd /usr/share/AAVMF/AAVMF_CODE.fd /usr/share/qemu-efi-aarch64/QEMU_EFI.fd; do [ -r "$f" ] && fw=$f && break; done; } ;;
  x86_64|amd64) qemu=qemu-system-x86_64; machine="q35"; cpu_model="host"
    [ -n "$fw" ] || { for f in /usr/local/share/qemu/edk2-x86_64-code.fd /opt/homebrew/share/qemu/edk2-x86_64-code.fd /usr/share/OVMF/OVMF_CODE.fd; do [ -r "$f" ] && fw=$f && break; done; } ;;
  *) die "unsupported cpu: $arch" ;;
esac
case "$os" in Darwin) accel=hvf ;; Linux) accel=kvm ;; *) die "unsupported os: $os (use Hyper-V on Windows)" ;; esac
[ -n "$fw" ] || die "UEFI firmware not found; pass --firmware /path/to/edk2-*-code.fd"

vmdir="$root/$name"
run mkdir -p "$vmdir"
# slirp gives the guest 10.0.2.15 by DHCP and the gateway/"host" 10.0.2.2.
sh "$common/render-seed.sh" --name "$name" --pubkey "$pubkey" --out "$vmdir/seed" --profile offline \
   --host-ip 10.0.2.2 --dhcp --iso "$vmdir/seed.iso"
run qemu-img convert -f qcow2 -O qcow2 "$base" "$vmdir/disk.qcow2"
run qemu-img resize "$vmdir/disk.qcow2" "${disk}G"

cat > "$vmdir/run.sh" <<EOF
#!/bin/sh
# Generated by new-lab-vm.sh. Headless; stop with: kill \$(cat "$vmdir/qemu.pid")  (freeze = savevm via the monitor socket)
exec $qemu -name $name -machine $machine -accel $accel -cpu $cpu_model -smp $cpus -m $mem \\
  -drive if=pflash,format=raw,readonly=on,file=$fw \\
  -drive if=virtio,format=qcow2,file=$vmdir/disk.qcow2 \\
  -drive if=virtio,format=raw,readonly=on,file=$vmdir/seed.iso \\
  -netdev user,id=n0,restrict=on,hostfwd=tcp:127.0.0.1:$ssh_port-:22 -device virtio-net-pci,netdev=n0 \\
  -nodefaults -display none -serial none -monitor unix:$vmdir/monitor.sock,server,nowait \\
  -pidfile $vmdir/qemu.pid -daemonize
EOF
chmod 700 "$vmdir/run.sh" 2>/dev/null || true
echo "created $vmdir/run.sh  (start it, then: ssh -p $ssh_port lab@127.0.0.1)"
echo "snapshot: qemu-img snapshot -c baseline-clean $vmdir/disk.qcow2   (with the VM stopped)"
echo "freeze: echo 'stop' | nc -U $vmdir/monitor.sock   (pauses the CPU; memory is kept)"
